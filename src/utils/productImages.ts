/**
 * Returns a high-res image URL for any menu item, checking explicit image, specific name, substring search, or category fallback.
 */
export function getProductImage(item: { name: string; category: string; image?: string }): string {
  if (item.image && item.image.trim() !== '') {
    return item.image;
  }
  
  if (SPECIFIC_ITEM_IMAGES[item.name]) {
    return SPECIFIC_ITEM_IMAGES[item.name];
  }

  // Exact lookup in lower case
  const lowerName = item.name.toLowerCase();
  for (const [key, url] of Object.entries(SPECIFIC_ITEM_IMAGES)) {
    if (key.toLowerCase() === lowerName) {
      return url;
    }
  }

  // Substring matching
  if (lowerName.includes('turkish coffee') || lowerName.includes('turkish')) {
    return SPECIFIC_ITEM_IMAGES['Turkish Coffee'];
  }
  if (lowerName.includes('french coffee')) {
    return SPECIFIC_ITEM_IMAGES['French Coffee'];
  }
  if (lowerName.includes('spanish latte')) {
    return lowerName.includes('iced') ? SPECIFIC_ITEM_IMAGES['Iced Spanish Latte'] : SPECIFIC_ITEM_IMAGES['Spanish Latte'];
  }
  if (lowerName.includes('matcha')) {
    return lowerName.includes('iced') ? SPECIFIC_ITEM_IMAGES['Iced Matcha Latte'] : SPECIFIC_ITEM_IMAGES['Matcha Latte'];
  }
  if (lowerName.includes('burger')) {
    return SPECIFIC_ITEM_IMAGES['Classic Burger'];
  }
  if (lowerName.includes('taco')) {
    return SPECIFIC_ITEM_IMAGES['Chicken Tacos (3 pcs)'];
  }
  if (lowerName.includes('quesadilla')) {
    return SPECIFIC_ITEM_IMAGES['Chicken Quesadilla'];
  }
  if (lowerName.includes('fajita')) {
    return SPECIFIC_ITEM_IMAGES['Chicken Fajita'];
  }
  if (lowerName.includes('toast') || lowerName.includes('avo')) {
    return SPECIFIC_ITEM_IMAGES['Avo Toast'];
  }
  if (lowerName.includes('omelette') || lowerName.includes('scramble') || lowerName.includes('egg')) {
    return SPECIFIC_ITEM_IMAGES['Classic Omelette'];
  }
  if (lowerName.includes('mojito')) {
    return SPECIFIC_ITEM_IMAGES['Classic Mojito'];
  }
  if (lowerName.includes('smoothie bowl') || lowerName.includes('bowl')) {
    return SPECIFIC_ITEM_IMAGES['Chocolate Bowl'];
  }
  if (lowerName.includes('wifi') || lowerName.includes('coworking') || lowerName.includes('table')) {
    return SPECIFIC_ITEM_IMAGES['Coworking Table Access (1 Hour)'];
  }

  if (CATEGORY_IMAGES[item.category]) {
    return CATEGORY_IMAGES[item.category];
  }

  return 'https://images.unsplash.com/photo-1501339847302-ac426a4a7cbb?w=600&auto=format&fit=crop&q=80';
}
